import { test,expect } from '@playwright/test'

test('Theme Switch toggles the entire catalog and stays synchronized with header', async ({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
  const app=page.locator('.app-shell')
  const themeSwitch=page.getByRole('switch',{name:'Tmavý režim'})
  const themeGroup=page.getByRole('group',{name:'Téma katalogu'})
  await expect(app).toHaveAttribute('data-theme','dark')
  await expect(themeSwitch).toBeChecked()
  await page.locator('.fs-theme-interactive').getByText('Tmavý režim').click()
  await expect(themeSwitch).not.toBeChecked()
  await expect(app).toHaveAttribute('data-theme','light')
  await expect(themeGroup.getByRole('button',{name:'☀ Light'})).toHaveAttribute('aria-pressed','true')
  await themeGroup.getByRole('button',{name:'☾ Dark'}).click()
  await expect(themeSwitch).toBeChecked()
  await expect(app).toHaveAttribute('data-theme','dark')
})

test('Theme Switch supports keyboard and accessible focus',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
  const themeSwitch=page.getByRole('switch',{name:'Tmavý režim'})
  await themeSwitch.focus()
  await expect(themeSwitch).toBeFocused()
  await expect(themeSwitch).toBeChecked()
  await page.keyboard.press('Space')
  await expect(themeSwitch).not.toBeChecked()
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme','light')
  await page.keyboard.press('Space')
  await expect(themeSwitch).toBeChecked()
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme','dark')
})

test('Theme Switch disables motion for reduced-motion preference',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/')
  await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
  const thumb=page.locator('.axo-theme-switch-orb')
  await expect(thumb).toHaveCSS('transition-duration','0s')
  await page.getByRole('switch',{name:'Tmavý režim'}).focus()
  await page.keyboard.press('Space')
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme','light')
})
