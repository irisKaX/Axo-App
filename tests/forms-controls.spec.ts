import { test, expect } from '@playwright/test'

for (const theme of ['light','dark']) {
  test(`${theme}: styled select supports keyboard interaction and escape`, async ({page})=>{
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    const select=page.getByRole('button',{name:/Město/})
    await select.focus()
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('listbox',{name:'Město'})).toBeVisible()
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await expect(page.getByText('Brno',{exact:true}).first()).toBeVisible()
    await expect(select).toHaveAttribute('aria-expanded','false')
    await select.click()
    await page.keyboard.press('Escape')
    await expect(select).toHaveAttribute('aria-expanded','false')
    await expect(select).toBeFocused()
    await expect(select).not.toHaveCSS('appearance','menulist')
  })

  test(`${theme}: checkbox, radio and switch update state, validation is accessible`,async({page})=>{
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    const subscribe=page.getByRole('checkbox',{name:'Odebírat novinky'})
    await page.getByText('Odebírat novinky',{exact:true}).click()
    await expect(subscribe).not.toBeChecked()
    const compact=page.getByRole('radio',{name:/Compact/})
    await page.getByText('Compact',{exact:true}).click()
    await expect(compact).toBeChecked()
    const autosave=page.getByRole('switch',{name:/Automatické ukládání/})
    await page.getByText('Automatické ukládání',{exact:true}).click()
    await expect(autosave).not.toBeChecked()
    const form=page.locator('form.fs-preview-controls')
    await form.getByRole('button',{name:'Ověřit formulář'}).click()
    await expect(form.getByText('Zadej platnou URL včetně https://')).toBeVisible()
    await expect(form.getByText('Vyber město',{exact:true}).last()).toBeVisible()
    await expect(form.getByText('Pro pokračování potvrď souhlas.')).toBeVisible()
    await form.getByRole('textbox',{name:/URL adresa analýzy/}).fill('https://www.o2.cz')
    await form.getByRole('button',{name:/Město analýzy/}).click()
    await form.getByRole('option',{name:'Praha'}).click()
    await form.getByRole('checkbox',{name:'Souhlasím s podmínkami'}).check({force:true})
    await form.getByRole('button',{name:'Ověřit formulář'}).click()
    await expect(form.getByRole('status')).toContainText('úspěšně ověřen')
    await form.getByRole('textbox',{name:/URL adresa analýzy/}).fill('not-a-url')
    await expect(form.getByRole('status')).not.toContainText('úspěšně ověřen')
  })
}
