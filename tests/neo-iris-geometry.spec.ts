import { test, expect } from '@playwright/test'

for (const theme of ['light','dark']) {
  test(`${theme}: fields share 24px geometry and one focus indicator`, async ({page}) => {
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    const text=page.getByRole('textbox',{name:'Hledat v nástrojích'})
    const area=page.getByRole('textbox',{name:'Poznámka k projektu'})
    const select=page.locator('.fs-select-layout').getByRole('button',{name:/Město/})
    for(const field of [text,area,select,page.getByRole('textbox',{name:'Success state'})]) {
      await expect(field).toHaveCSS('border-radius','24px')
      await page.keyboard.press('Tab')
      await field.focus()
      await expect(field).toHaveCSS('outline-style','none')
      await expect(field).toHaveCSS('border-top-color','rgba(0, 0, 0, 0)')
      await expect(field).toHaveCSS('box-shadow',/inset/)
    }
    await expect(text).toHaveCSS('height','52px')
    await expect(select).toHaveCSS('height','52px')
    await expect(page.locator('.fs-form-preview')).toHaveCSS('border-radius','32px')
    await expect(page.getByText('NÁVRH K VIZUÁLNÍMU SCHVÁLENÍ',{exact:true})).toBeVisible()
  })
}

for (const theme of ['light','dark']) {
  test(`${theme}: select skips disabled choices and Tab continues after the field`, async ({page}) => {
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    const select=page.locator('.fs-select-layout').getByRole('button',{name:/Město/})
    await select.focus()
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('End')
    await expect(page.getByRole('option',{name:'Ostrava'})).toBeFocused()
    await expect(page.getByRole('option',{name:'Jiné město'})).toBeDisabled()
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('option',{name:'Praha'})).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(page.getByRole('textbox',{name:'Poznámka k projektu'})).toBeFocused()
    await expect(page.getByRole('listbox')).toHaveCount(0)
  })

  test(`${theme}: validation is local, focuses errors, and clears stale status`, async ({page}) => {
    const writes:string[]=[]
    let interacting=false
    page.on('request',request=>{if(!['GET','HEAD'].includes(request.method())||(interacting&&['document','fetch','xhr'].includes(request.resourceType())))writes.push(request.url())})
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    const form=page.locator('.fs-preview-controls')
    const url=form.getByRole('textbox',{name:/URL adresa analýzy/})
    const submit=form.getByRole('button',{name:'Ověřit formulář'})
    interacting=true
    await submit.click()
    await expect(url).toBeFocused()
    await expect(url).toHaveAttribute('aria-invalid','true')
    await expect(url).toHaveCSS('outline-style','none')
    await expect(url).toHaveCSS('border-top-color','rgba(0, 0, 0, 0)')
    await url.fill('javascript:alert(1)')
    await submit.click()
    await expect(url).toHaveAttribute('aria-invalid','true')
    await url.fill('https://www.o2.cz')
    await submit.click()
    const city=form.getByRole('button',{name:/Město analýzy/})
    await expect(city).toBeFocused()
    await city.click()
    await page.getByRole('option',{name:'Praha'}).click()
    await submit.click()
    const consent=form.getByRole('checkbox',{name:/Souhlasím/})
    await expect(consent).toBeFocused()
    await expect(consent).toHaveAccessibleDescription('Pro pokračování potvrď souhlas.')
    await page.keyboard.press('Space')
    await expect(consent).toBeChecked()
    await expect(form.getByRole('status')).toContainText('Vše je připraveno')
    await submit.click()
    await expect(form.getByRole('status')).toContainText('úspěšně ověřen')
    await url.fill('https://example.cz')
    await expect(form.getByRole('status')).toContainText('Vše je připraveno')
    await url.fill('invalid')
    await expect(form.getByRole('status')).toContainText('Oprav označená pole')
    expect(writes).toEqual([])
  })
}

for (const theme of ['light','dark']) for (const viewport of [{width:390,height:844},{width:1280,height:900},{width:1600,height:1000}]) {
  test(`${theme}/${viewport.width}: responsive forms and choice states`, async ({page}, testInfo) => {
    await page.setViewportSize(viewport)
    await page.goto('/')
    await page.getByRole('group',{name:'Téma katalogu'}).getByRole('button',{name:theme==='light'?'☀ Light':'☾ Dark',exact:true}).click()
    await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
    await expect(page.locator('.fs-panel').first()).toHaveCSS('border-radius','32px')
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    const check=page.getByRole('checkbox',{name:'Odebírat novinky'})
    await check.focus();await page.keyboard.press('Space');await expect(check).not.toBeChecked()
    await expect(page.getByRole('checkbox',{name:'Nedostupná možnost'})).toBeDisabled()
    await expect(page.getByRole('checkbox',{name:'Uzamčená preference'})).toBeChecked()
    await expect(page.getByRole('radio',{name:/Automaticky/})).toBeDisabled()
    const radio=page.getByRole('radio',{name:/Comfortable/})
    await radio.focus();await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('radio',{name:/Compact/})).toBeChecked()
    const toggle=page.getByRole('switch',{name:/Notifikace/})
    await toggle.focus();await page.keyboard.press('Space');await expect(toggle).toBeChecked()
    const select=page.locator('.fs-select-layout').getByRole('button',{name:/Město/})
    await select.click()
    const menu=page.getByRole('listbox',{name:'Město',exact:true})
    await expect(menu).toHaveCSS('border-radius','24px')
    const box=await menu.boundingBox();expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(viewport.width)
    await testInfo.attach('open-select',{body:await page.screenshot({fullPage:true}),contentType:'image/png'})
    await page.keyboard.press('Escape')
    await page.emulateMedia({reducedMotion:'reduce'})
    await expect(page.locator('.fc-switch-thumb').first()).toHaveCSS('transition-duration','0s')
    await testInfo.attach('complete-form',{body:await page.locator('.fs-form-preview').screenshot(),contentType:'image/png'})
  })
}

test('radius catalog consumes the shared scale including pill and round',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Spacing & Grid',exact:true}).click()
  const entries=page.locator('.sg-radius-card')
  await expect(entries).toHaveCount(8)
  await expect(entries.filter({hasText:'radius.lg'})).toContainText('Inputy, Select, Textarea')
  const round=page.locator('.sg-radius-object--round')
  const box=await round.boundingBox();expect(box!.width).toBe(box!.height)
  await expect(round).toHaveCSS('border-radius','50%')
  for(const [token,value]of Object.entries({xs:'8px',sm:'12px',md:'18px',lg:'24px',xl:'32px',xxl:'40px',pill:'9999px',round:'50%'})){
    expect(await page.locator('.app-shell').evaluate((el,key)=>getComputedStyle(el).getPropertyValue(key).trim(),'--radius-'+token)).toBe(value)
  }
})

test('field focus remains visible with forced system colors',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Components / Inputs & Forms',exact:true}).click()
  await page.emulateMedia({forcedColors:'active'})
  await page.keyboard.press('Tab')
  const field=page.getByRole('textbox',{name:'Hledat v nástrojích'})
  await field.focus()
  await expect(field).toHaveCSS('outline-style','solid')
  await expect(field).toHaveCSS('outline-width','2px')
  await expect(field).toHaveCSS('outline-offset','-2px')
  await expect(field).toHaveCSS('box-shadow','none')
})


test('button geometry and visible tooltip consume their purpose-specific radius tokens',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Components / Buttons',exact:true}).click()
  const text=page.locator('.bs-variants .axo-button--primary')
  await expect(text).toHaveCSS('height','40px')
  await expect(text).toHaveCSS('border-radius','9999px')
  const icon=page.locator('.bs-motion-grid').getByRole('button',{name:'Kopírovat URL',exact:true})
  await expect(icon).toHaveCSS('height','44px')
  await expect(icon).toHaveCSS('width','44px')
  await expect(icon).toHaveCSS('border-radius','50%')
  await icon.hover()
  await expect.poll(()=>icon.evaluate(el=>getComputedStyle(el,'::after').opacity)).toBe('1')
  expect(await icon.evaluate(el=>getComputedStyle(el,'::after').borderRadius)).toBe('12px')
  expect(await icon.evaluate(el=>getComputedStyle(el,'::after').content)).toContain('Kopírovat URL')
})
